// Pre-build step: refresh the link-preview (Open Graph) snapshot.
//
// Produces two artifacts consumed by the /products/$slug head():
//   public/og/<name>.jpg             downscaled JPEGs (WhatsApp reliably
//                                    renders previews only under ~300KB; the
//                                    CDN originals are ~900KB PNGs)
//   src/lib/og-catalog.generated.ts  slug -> { name, description, image,
//                                    minPricePaise } so the worker can render
//                                    per-product OG tags WITHOUT fetching the
//                                    API at request time (same-zone fetch loop)
//
// The catalog is embedded at build time on purpose: product changes reach link
// previews on the next deploy. Never fails the build — on any error the
// previous snapshot is kept (first run: empty, site-card fallback).
//
// Resizing uses macOS `sips` (all deploys build locally on the Mac). Where
// sips is unavailable the snapshot falls back to the original CDN URLs.

import { execFile } from "node:child_process";
import { mkdir, readFile, writeFile, rm } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const run = promisify(execFile);
const appDir = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const API_URL =
  process.env.OG_API_URL ??
  process.env.VITE_API_BASE_URL ??
  "https://api.aarogyaruchi.com";
const OG_DIR = path.join(appDir, "public", "og");
const SNAPSHOT = path.join(appDir, "src", "lib", "og-catalog.generated.ts");
const MAX_EDGE = 800;
const JPEG_QUALITY = 72;

const hasSips = process.platform === "darwin";

async function writeIfChanged(file, contents) {
  const previous = existsSync(file) ? await readFile(file, "utf8") : null;
  if (previous === contents) return false;
  await writeFile(file, contents);
  return true;
}

async function fetchJson(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url} -> ${res.status}`);
  return res.json();
}

async function imageSize(file) {
  const { stdout } = await run("sips", [
    "-g",
    "pixelWidth",
    "-g",
    "pixelHeight",
    file,
  ]);
  const width = /pixelWidth: (\d+)/.exec(stdout)?.[1];
  const height = /pixelHeight: (\d+)/.exec(stdout)?.[1];
  return width && height
    ? { width: Number(width), height: Number(height) }
    : null;
}

async function resizeToJpeg(sourceUrl, outFile, tmpFile) {
  const res = await fetch(sourceUrl);
  if (!res.ok) throw new Error(`${sourceUrl} -> ${res.status}`);
  await writeFile(tmpFile, Buffer.from(await res.arrayBuffer()));
  await run("sips", [
    "-Z",
    String(MAX_EDGE),
    "--setProperty",
    "format",
    "jpeg",
    "--setProperty",
    "formatOptions",
    String(JPEG_QUALITY),
    tmpFile,
    "--out",
    outFile,
  ]);
}

async function main() {
  let products;
  try {
    products = (await fetchJson(`${API_URL}/v1/products`)).products ?? [];
  } catch (err) {
    console.warn(
      `[og-catalog] catalog fetch failed (${err.message}); keeping previous snapshot`,
    );
    return;
  }

  await mkdir(OG_DIR, { recursive: true });
  const tmp = path.join(OG_DIR, ".tmp-src");
  const snapshot = {};

  for (const product of products) {
    if (!product.slug) continue;
    const minPricePaise = (product.variants ?? []).reduce(
      (min, v) => Math.min(min, v.price_paise ?? Number.MAX_SAFE_INTEGER),
      Number.MAX_SAFE_INTEGER,
    );

    let image = null;
    let ogDims = null;
    if (product.image_url) {
      const key = path
        .basename(new URL(product.image_url).pathname)
        .replace(/\.[^.]+$/, "");
      const outFile = path.join(OG_DIR, `${key}.jpg`);
      try {
        if (hasSips) {
          await resizeToJpeg(product.image_url, outFile, tmp);
          image = `/og/${key}.jpg`;
          ogDims = await imageSize(outFile);
        } else {
          image = product.image_url; // no resizer: original URL, heavy but works
        }
      } catch (err) {
        console.warn(
          `[og-catalog] image for ${product.slug} failed (${err.message}); using site card`,
        );
      }
    }

    snapshot[product.slug] = {
      name: product.name ?? product.slug,
      description: product.description ?? "",
      image,
      imageWidth: ogDims?.width ?? null,
      imageHeight: ogDims?.height ?? null,
      minPricePaise: Number.isFinite(minPricePaise) ? minPricePaise : 0,
    };
  }
  await rm(tmp, { force: true });

  const ts =
    "// AUTO-GENERATED by scripts/embed-og-catalog.mjs — do not edit.\n" +
    "// Refreshed on every build from the live catalog; committed so fresh\n" +
    "// clones typecheck. Link previews pick up product changes on deploy.\n\n" +
    "export type OgProduct = {\n  name: string\n  description: string\n  /** Site-relative /og/<name>.jpg, or the CDN original when sips was unavailable. */\n  image: string | null\n  imageWidth: number | null\n  imageHeight: number | null\n  minPricePaise: number\n}\n\n" +
    "export const OG_CATALOG: Record<string, OgProduct> = " +
    JSON.stringify(snapshot, null, 2) +
    "\n";

  const changed = await writeIfChanged(SNAPSHOT, ts);
  console.log(
    `[og-catalog] ${Object.keys(snapshot).length} products embedded${changed ? "" : " (snapshot unchanged)"}`,
  );
}

main().catch((err) => {
  console.warn(`[og-catalog] unexpected failure: ${err.message}; keeping previous snapshot`);
});
